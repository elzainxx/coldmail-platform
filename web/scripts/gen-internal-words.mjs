// gen-internal-words.mjs — the deny-list of the platform's INTERNAL words that no screen may show (Phase 6, chunk A8).
//
//   node scripts/gen-internal-words.mjs          prints the JSON the committed file must equal
//   node scripts/gen-internal-words.mjs --write  rewrites src/copy/internal-words.json
//   node scripts/gen-internal-words.mjs --check  exits 1 (naming the difference) when the committed file is stale
//
// WHERE THE WORDS COME FROM (never typed by hand, so a new code cannot be forgotten):
//   * the error table of Docs/jobs-api.md: every `code` and every word of the `not_allowed` reason cell;
//   * the charge table internal/charge/rules.psv: rule ids (M1-01 ... P-10), units (m1_own ...), and every state or reason that is a snake_case token;
//   * a short list of names of the platform's tables and roles that must never be shown.
// Only tokens with an underscore (or a rule id) are listed: a plain English word such as `busy` may appear in a sentence, and the catalogue test already checks every string of the catalogue against the codes.
// The e2e scope reads this file to assert that no rendered page holds one of the words (web/e2e/support/copy.ts).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const OUT = fileURLToPath(new URL('../src/copy/internal-words.json', import.meta.url))

const STATIC = [
  'module_id', 'job_transition', 'job_events', 'job_rows', 'job_results', 'job_items', 'job_unit_prices', 'user_settings', 'user_settings_history',
  'suppression_removals', 'platform_app', 'platform_owner', 'send_managed', 'send_byo', 'idempotency_key', 'preview_fingerprint', 'frozen_settings',
  'content_cleared_at', 'unsubscribe_url', 'email_norm', 'email_raw', 'public_users', 'auth_users',
]

export function buildWords() {
  const words = new Set(STATIC)
  const api = readFileSync(`${ROOT}/Docs/jobs-api.md`, 'utf8')
  for (const line of api.split('\n')) {
    const m = /^\| (\d{3}) \| `([a-z_]+)` \|/.exec(line)
    if (!m) continue
    if (m[2].includes('_')) words.add(m[2])
    if (m[2] === 'not_allowed') {
      const cells = line.split('|')
      for (const r of (cells[cells.length - 2] ?? '').matchAll(/`([a-z_]+)`/g)) if (r[1] !== 'reason' && r[1].includes('_')) words.add(r[1])
    }
  }
  const rules = readFileSync(`${ROOT}/internal/charge/rules.psv`, 'utf8')
  for (const line of rules.split('\n')) {
    if (!line.trim() || line.startsWith('id|')) continue
    const cells = line.split('|')
    // id|module|state|reason|cache|skip|origin|decision|unit|note
    if (/^[A-Z0-9]+-[0-9A-Z]+$/.test(cells[0] ?? '')) words.add(cells[0].toLowerCase())
    for (const i of [2, 3, 8]) {
      const c = (cells[i] ?? '').trim()
      if (/^[a-z0-9]+(_[a-z0-9]+)+$/.test(c)) words.add(c)
    }
  }
  return [...words].map((w) => w.toLowerCase()).sort()
}

export function render() {
  return (
    JSON.stringify(
      {
        _status: 'GENERATED by scripts/gen-internal-words.mjs from Docs/jobs-api.md and internal/charge/rules.psv: do not edit by hand (src/copy/internal-words.test.ts fails when it is stale). The e2e copy check (web/e2e/support/copy.ts) and the catalogue test read the `words`.',
        words: buildWords(),
      },
      null,
      2,
    ) + '\n'
  )
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const arg = process.argv[2]
  if (arg === '--write') {
    writeFileSync(OUT, render())
    console.log(`wrote ${OUT}`)
  } else if (arg === '--check') {
    const have = readFileSync(OUT, 'utf8')
    const want = render()
    if (have !== want) {
      console.error('internal-words.json is stale: run `node scripts/gen-internal-words.mjs --write` and commit the result')
      process.exit(1)
    }
    console.log('internal-words.json is up to date')
  } else {
    process.stdout.write(render())
  }
}

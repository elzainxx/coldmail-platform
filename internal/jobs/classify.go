// The states of a row of platform.job_rows (the CHECK job_rows_state_vocabulary).
const (
	StatePending    = "pending"    // will reach the module
	StateMalformed  = "malformed"  // the platform's address rule refused it: counted and skipped, never sent, never charged (charge row P-08)
	StateDuplicate  = "duplicate"  // repeats an earlier pending row's normalised address (P-07)
	StateSuppressed = "suppressed" // the user's own suppression list, applied at confirm (P-SUP)
	StateExcluded   = "excluded"   // a chained send's source verdict that was not selected (P-EXC)

	// The two states a SEND job's confirm gives a pending row its templates cannot be rendered for (Phase 5 S2, platform_0019). Neither is ever given a public.job_items row, reserved or charged.
	StateMissingField = "missing_field" // the row lacks a merge field the templates need and give no fallback for; the row's reason names the fields, never a value (P-09)
	StateUnrenderable = "unrenderable"  // the row's rendered message is one the shared table refuses (checkRendered); the row's reason is the word of the refusal (P-10)
)

// Two malformed reasons the platform adds to norm's words (norm.Reasons, norm.SyntaxReasons) for text the table cannot keep. A reason is always a word, never the address.
const (
	ReasonTooLong     = "too_long"     // more than MaxRawBytes bytes of text: job_rows keeps at most that much, and norm's IDNA step is quadratic on long input
	ReasonInvalidText = "invalid_text" // a NUL or bytes that are not UTF-8: PostgreSQL text cannot hold them
)

// The result labels of the platform's own outcomes that are NOT rows of the charge table (internal/charge/rules.psv): they are labels on a free result, written by the store.
const (
	RuleSuppressed = "P-SUP"
	RuleExcluded   = "P-EXC"
)

// classified is a row of platform.job_rows as it will be written.
type classified struct {
	ID          string
	Ordinal     int    // 1-based, in input order
	Raw         string // what job_rows.email_raw keeps: the address as typed (cleaned only when it holds text the database cannot store)
	Norm        string // norm.Validate's output; "" for a malformed row (job_rows.email_norm is then NULL)
	State       string
	Reason      string // the malformed reason word, or the excluded verdict; "" otherwise
	DuplicateOf string // the id of the earlier pending row this one repeats
	Fields      string // the JSON object of merge data
	SourceItem  string // chained: the source job's item_ref this row came from
}

// judge decides one typed address: the text to keep as email_raw, the normalised address and, when the address is refused, the reason word (and no normalised address). It runs the platform's whole
// address rule, norm.Validate (norm/v1, then module 1's syntax layer), exactly once per address. The length is bounded BEFORE the rule runs (norm's own doc: a caller that reads user files
// bounds the length of a row first), and text the database cannot store is refused before it reaches it.
func judge(raw string) (stored, normalised, reason string) {
	if len(raw) > MaxRawBytes {
		return cutText(cleanText(raw), MaxRawBytes), "", ReasonTooLong
	}
	if !textOK(raw) {
		return cleanText(raw), "", ReasonInvalidText
	}
	n, err := norm.Validate(raw)
	if err != nil {
		r, ok := norm.ReasonAny(err)
		if !ok || r == "" {
			r = norm.ReasonInternal // a refusal that is neither half of the rule: still a refusal, and never an address
		}
		return raw, "", string(r)
	}
	return raw, n, ""
}

// cleanText makes a string storable: NULs removed, bytes that are not UTF-8 replaced by U+FFFD. It is for text of a malformed row, which is kept only so that the user can find the line.
func cleanText(s string) string {
	return strings.ToValidUTF8(strings.ReplaceAll(s, "\x00", ""), string(rune(0xFFFD)))
}

// cutText shortens s to at most n bytes without splitting a code point.
func cutText(s string, n int) string {
	if len(s) <= n {
		return s
	}
	for n > 0 && !utf8.RuneStart(s[n]) {
		n--
	}
	return s[:n]
}

// classifyRows classifies the list a user supplied, once: pending, malformed (with the reason word) or duplicate (with the id of the earlier pending row it repeats). Ids are generated by newID so
// that a duplicate can name the row it repeats. Ordinals are 1-based in input order. A row whose merge data breaks a limit fails the whole list with an ErrBadRequest naming the row's ordinal.
func classifyRows(in []RowIn, newID func() string) ([]classified, error) {
	out := make([]classified, len(in))
	firstOf := make(map[string]string, len(in)) // normalised address -> id of the first pending row that has it
	for i, r := range in {
		ordinal := i + 1
		fields, err := checkFields(ordinal, r.Fields)
		if err != nil {
			return nil, err
		}
		c := classified{ID: newID(), Ordinal: ordinal, Fields: fields}
		c.Raw, c.Norm, c.Reason = judge(r.Email)
		switch {
		case c.Reason != "":
			c.State, c.Norm = StateMalformed, ""
		default:
			if first, dup := firstOf[c.Norm]; dup {
				c.State, c.DuplicateOf = StateDuplicate, first
			} else {
				c.State = StatePending
				firstOf[c.Norm] = c.ID
			}
		}
		out[i] = c
	}
	return out, nil
}

// The verdicts of module 1 a chained send selects from.
const (
	VerdictValid   = "valid"
	VerdictInvalid = "invalid"
	VerdictRisky   = "risky"
	VerdictUnknown = "unknown"
)

// Verdicts lists the four verdicts a verify job's results carry, in the order previews report them.
func Verdicts() []string { return []string{VerdictValid, VerdictInvalid, VerdictRisky, VerdictUnknown} }

// selects says whether a chained send sends to an address whose source verdict is v: valid and risky always, unknown only when the user chose to include it, invalid never. A verdict
// this store does not know is not selected: a result it cannot read is never sent to.
func selects(v, unknownChoice string) bool {
	switch v {
	case VerdictValid, VerdictRisky:
		return true
	case VerdictUnknown:
		return unknownChoice == UnknownInclude
	}
	return false
}

// sourceResult is one module result of the source job of a chained send.
type sourceResult struct {
	ItemRef string // the source job's item_ref (its job_rows.id)
	Email   string // the address of the result
	Verdict string // module_state
}

// classifyChain turns the module results of a verify job into the rows of a chained send, in the source's order: pending when the verdict is selected, excluded (reason = the verdict) when it is
// not. email_norm is the result's address. A pending row repeats nothing the source did not (its duplicates never reached the module and are not results), but a repeat is still caught.
func classifyChain(res []sourceResult, unknownChoice string, newID func() string) []classified {
	out := make([]classified, len(res))
	firstOf := make(map[string]string, len(res))
	for i, r := range res {
		c := classified{ID: newID(), Ordinal: i + 1, Fields: "{}", SourceItem: r.ItemRef}
		switch {
		case len(r.Email) > MaxRawBytes:
			c.Raw, c.State, c.Reason = cutText(cleanText(r.Email), MaxRawBytes), StateMalformed, ReasonTooLong
		case !textOK(r.Email) || strings.TrimSpace(r.Email) == "":
			c.Raw, c.State, c.Reason = cleanText(r.Email), StateMalformed, ReasonInvalidText
		default:
			c.Raw, c.Norm = r.Email, r.Email
			if selects(r.Verdict, unknownChoice) {
				if first, dup := firstOf[c.Norm]; dup {
					c.State, c.DuplicateOf = StateDuplicate, first
				} else {
					c.State = StatePending
					firstOf[c.Norm] = c.ID
				}
			} else {
				c.State, c.Reason = StateExcluded, excludedReason(r.Verdict)
			}
		}
		if c.Raw == "" { // job_rows.email_raw is NOT NULL and a result with no text at all still has a row
			c.Raw = "-"
		}
		out[i] = c
	}
	return out
}

// excludedReason is the reason of an excluded row: the verdict itself (a short word of the module's vocabulary), or "unclassified" for text that is not one.
func excludedReason(verdict string) string {
	if verdict == "" || len(verdict) > 64 || !textOK(verdict) {
		return "unclassified"
	}
	return verdict
}

// resultRule is the rule label of the platform's own result for a row in state: the charge table's row for malformed (P-08), duplicate (P-07), cancelled (P-01), missing_field (P-09) and unrenderable (P-10), read from the table
// (internal/charge) and required to be FREE there, and the two labels the store owns for suppressed and excluded rows.
func resultRule(state string) (string, error) {
	switch state {
	case StateSuppressed:
		return RuleSuppressed, nil
	case StateExcluded:
		return RuleExcluded, nil
	}
	d := charge.Decide(charge.Outcome{Module: "platform", State: state})
	if d.Kind != charge.Free {
		return "", fmt.Errorf("jobs: the charge table does not make a platform %q outcome free (it says %s, rule %s): a platform result is never charged", state, d.Kind, d.Rule)
	}
	return d.Rule, nil
}
